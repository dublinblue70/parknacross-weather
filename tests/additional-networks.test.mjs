import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const worker=fs.readFileSync(new URL('../_worker/worker.mjs',import.meta.url),'utf8');
const start=worker.indexOf('function iewnRealtimeText('),end=worker.indexOf('async function publishAdditionalNetworks(',start);
assert.ok(start>=0&&end>start);
const helpers=vm.runInNewContext(worker.slice(start,end)+'\n({iewnRealtimeText,openweatherMeasurement,vweatherParameters})',{Intl,Date,URLSearchParams,usableNumber:v=>v!==null&&v!==undefined&&v!==''&&Number.isFinite(Number(v))});
const observation={epoch:1795766400,rainToday:2.54,rainHour:.254,reading:{temperature_c:10,humidity:85,wind_speed_kmh:36,wind_gust_kmh:54,wind_direction_deg:270,pressure_hpa:1013,rain_rate_mm_h:1.2,solar_w_m2:0,uv_index:0,piezo_daily_mm:99}};
const fields=helpers.iewnRealtimeText(observation).trim().split(' ');
assert.equal(fields.length,58);
assert.equal(fields[9],'2.5');assert.equal(fields[11],'W');assert.equal(fields[22],'-');
const o=helpers.openweatherMeasurement('fixture',observation);
assert.equal(o.wind_speed,10);assert.equal(o.wind_gust,15);assert.equal(o.rain_1h,.254);
const v=helpers.vweatherParameters('fixture','dummy',observation);
assert.equal(v.get('tempf'),'50.00');assert.equal(v.get('dailyrainin'),'0.1000');assert.equal(v.get('rainin'),'0.0100');
const missing={...observation,rainToday:null,rainHour:null};
assert.equal(helpers.openweatherMeasurement('fixture',missing).rain_1h,undefined);
assert.equal(helpers.vweatherParameters('fixture','dummy',missing).has('rainin'),false);
assert.equal(helpers.iewnRealtimeText(missing).split(' ')[9],'-');
const html=fs.readFileSync(new URL('../networks.html',import.meta.url),'utf8');
const active=html.split('id="connectedNetworks"')[1].split('</section>')[0];
assert.equal((active.match(/<article class="station-external-network"/g)||[]).length,11);
assert.ok(active.includes('href="https://vweatherstation.com/pws/station/parknacross/"'));
const pending=html.split('id="pendingNetworksHeading"')[1].split('</section>')[0];
assert.equal((pending.match(/<article class="station-external-network"/g)||[]).length,2);
assert.ok(!pending.includes("VWeatherStation"));
assert.ok(!pending.includes("OpenWeatherMap"));
const activeIds=[...active.matchAll(/<a class="station-external-network-link" id="([^"]+)"/g)].map(match=>match[1]);
assert.equal(activeIds[6],"stationOpenWeatherLink");
assert.ok(active.includes('id="stationOpenWeatherLink" href="https://openweathermap.org/"'));
assert.ok(active.includes("Provider website"));
assert.ok(!active.includes("appid="));
assert.match(html,/id="pendingNetworksHeading">In preparation/);
assert.match(html,/Station observations are not yet published/);
console.log('PASS: additional networks preserve rainfall provenance, correct units, missing values and separate pending links.');
