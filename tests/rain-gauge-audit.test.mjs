import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const script=fs.readFileSync(new URL("../rain-gauge-audit.js",import.meta.url),"utf8");
const context={window:{},document:{addEventListener(){}},Date,Intl,Map,Math,Number};
vm.createContext(context);vm.runInContext(script,context);
const x=context.window.ParknacrossRainGaugeAudit;
const start=Date.parse("2026-11-03T00:00:00Z")/1000,split=Date.parse("2026-11-03T13:00:00Z")/1000;
const row=(epoch,rain_daily_mm)=>({epoch,rain_daily_mm});
const day={readings:[row(start,0),row(start+300,.1),row(split-600,2),row(split+300,0),row(split+600,.1),row(split+3600,.8)],summary:{rain_mm:3.5}};
const result=x.analyseChangeover(day);
assert.equal(result.before.observedIncreaseMm,2);
assert.equal(result.after.observedIncreaseMm,.8);
assert.equal(result.estimateMm,2.8);
assert.equal(result.recordedMm,3.5);
assert.equal(result.verified,false,"Reconstructed counters are not an independently calibrated daily total");
assert.ok(result.warnings.length,"Archive gaps are disclosed");
const reset=x.analyseChangeover({readings:[...day.readings,row(split+3900,.1)]});
assert.equal(reset.after.resets,1);
assert.equal(reset.estimateMm,null);
const recent=x.analyseRecentTips([row(split+300,0),row(split+600,.1),row(split+900,.2)],split+1000);
assert.equal(recent.observedIncreaseMm,.2);
assert.equal(recent.physicallyVerified,false);
assert.equal(recent.feedFresh,true);
const dry=x.analyseRecentTips([row(split+300,0),row(split+600,0)],split+900);
assert.equal(dry.lastRise,null);
assert.equal(dry.physicallyVerified,false);
const missing=x.analyseChangeover({readings:[]});
assert.equal(missing.estimateMm,null);
console.log("PASS: read-only gauge audit recognises distinct sensor counters, gaps, resets and unverified physical sensor status.");
